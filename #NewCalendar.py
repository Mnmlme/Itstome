DAYS_OF_WEEK = ["Воскресенье", "Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота"]

def get_exact_astronomical_dates(year):
   """
    Астрофизический расчет всех 8 точек Колеса Года по эфемеридам NASA (библиотека ephem).
    Вычисляет точные моменты, когда Солнце пересекает эклиптические градусы:
    0° (Весна), 45° (Имболк), 90° (Лето), 135° (Бельтайн), 180° (Осень), 225° (Ламмас), 270° (Зима), 315° (Самайн).
    """
   import ephem
    
   # Переводим числовой год в текст, чтобы библиотека ephem считала его корректно
   year_str = str(year)
   prev_year_str = str(year - 1)
    
    # Расчет основных кардинальных точек (равноденствия и солнцестояния)
   spring_eq = ephem.next_vernal_equinox(year_str).datetime().date()      # 0°
   summer_sol = ephem.next_summer_solstice(year_str).datetime().date()    # 90°
   autumn_eq = ephem.next_autumnal_equinox(year_str).datetime().date()    # 180°
    # Зимнее солнцестояние — это стык циклов (берем солнцестояние конца предыдущего года)
   winter_sol = ephem.next_winter_solstice(prev_year_str).datetime().date() # 270°
    
    # Математическое вычисление кросс-четвертных точек (точные середины по дням)
   imbolc_date = winter_sol + datetime.timedelta(days=int((spring_eq - winter_sol).days / 2))
   beltane_date = spring_eq + datetime.timedelta(days=int((summer_sol - spring_eq).days / 2))
   lammas_date = summer_sol + datetime.timedelta(days=int((autumn_eq - summer_sol).days / 2))
    
   next_winter = ephem.next_winter_solstice(year_str).datetime().date()
   samhain_date = autumn_eq + datetime.timedelta(days=int((next_winter - autumn_eq).days / 2))
    
   return {
        "Йоль (Зимнее Солнцестояние - Точка Ноль)": winter_sol,
        "Истинный Имболк (Стык зимы и весны)": imbolc_date,
        "Весеннее Равноденствие (Остара)": spring_eq,
        "Истинный Бельтайн (Стык весны и лета)": beltane_date,
        "Летнее Солнцестояние (Гелиос)": summer_sol,
        "Истинный Ламмас (Стык лета и осени)": lammas_date,
        "Осеннее Равноденствие (Мабон)": autumn_eq,
        "Истинный Самайн (Стык осени и предзимья)": samhain_date
    }

def convert_to_new_time(dt):
    year = dt.year
    if dt.month == 12 and dt.day >= 21:
        cycle_year = year + 1
    else:
        cycle_year = year
        
    is_leap = (cycle_year % 4 == 0 and cycle_year % 100 != 0) or (cycle_year % 400 == 0)
    
    dec_21 = datetime.date(cycle_year - 1, 12, 21)
    dec_22 = datetime.date(cycle_year - 1, 12, 22)
    
    if dt == dec_21:
        return {"type": "ДВВ", "date_str": "День вне времени (Йоль)", "day_name": "Вне времени", "is_holiday": True, "info": "Точка Ноль. Всемирный день тишины, искусства и медитации."}
    if is_leap and dt == dec_22:
        return {"type": "ДВВ", "date_str": "Второй День вне времени", "day_name": "Вне времени", "is_holiday": True, "info": "Високосный день расширения времени."}
        
    start_date = dec_21 if is_leap else dec_22
    day_of_year = (dt - start_date).days + 1
    
    month_idx = (day_of_year - 1) // 28
    day_in_month = (day_of_year - 1) % 28 + 1
    day_week_idx = (day_in_month - 1) % 7
    day_name = DAYS_OF_WEEK[day_week_idx]
    
    is_global_holiday = (month_idx == 0 and day_in_month <= 13)
    is_regular_weekend = day_week_idx in [0, 3, 6]
    
    status = "Эффективный рабочий день"
    if is_global_holiday:
        status = "✨ Великие Новогодние Каникулы! ✨"
    elif is_regular_weekend:
        status = f"Законный выходной ({day_name})"
        
    astro_dates = get_exact_astronomical_dates(cycle_year)
    matching_event = None
    for name, g_date in astro_dates.items():
        if dt == g_date:
            matching_event = name
            status = f"🌟 ПРИРОДНЫЙ ПИК: {name}! 🌟"
            
    return {
        "type": "REGULAR",
        "month_idx": month_idx,
        "month_name": MONTH_NAMES[month_idx],
        "day_in_month": day_in_month,
        "day_name": day_name,
        "is_holiday": is_global_holiday or is_regular_weekend or (matching_event is not None),
        "info": status,
        "event": matching_event
    }

